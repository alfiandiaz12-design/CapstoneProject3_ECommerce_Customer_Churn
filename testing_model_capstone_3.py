import shap

# Ambil pipeline XGBoost yang sudah di-fit dari dalam VotingClassifier
xgb_pipeline_fitted = soft_voting_model.named_estimators_['xgb']
preprocessor_fitted = xgb_pipeline_fitted.named_steps['preprocessor']
model_xgb_raw = xgb_pipeline_fitted.named_steps['model']

# Transform X_test (data test asli dari data_test_5.csv), JANGAN fit ulang
X_test_transformed = preprocessor_fitted.transform(X_test)

# Kalau hasil transform sparse matrix, ubah ke dense
if hasattr(X_test_transformed, "toarray"):
    X_test_transformed = X_test_transformed.toarray()

feature_names = preprocessor_fitted.get_feature_names_out()
X_test_transformed_df = pd.DataFrame(X_test_transformed, columns=feature_names)
X_test_transformed_df.columns = X_test_transformed_df.columns.str.replace('one hot__', '', regex=False)
X_test_transformed_df.columns = X_test_transformed_df.columns.str.replace('remainder__', '', regex=False)

# Inisialisasi TreeExplainer dengan model XGBoost hasil ekstraksi
explainer = shap.TreeExplainer(model_xgb_raw)
shap_values = explainer(X_test_transformed_df)

# Untuk klasifikasi biner, ambil kelas 1 (Churn) kalau output 3 dimensi
if len(shap_values.shape) == 3:
    shap_values_to_plot = shap_values[:, :, 1]
else:
    shap_values_to_plot = shap_values

plt.figure(figsize=(10, 8))
shap.summary_plot(shap_values_to_plot, X_test_transformed_df, show=False)
plt.subplots_adjust(left=0.35)
plt.title('SHAP Summary Plot - XGBoost (Extracted from Soft Voting)')
plt.show()