"""#Soft Voting Testing Final Model

"""

drive.mount('/content/drive')
path = '/content/drive/MyDrive/Dataset Capstone 3/'
model_path = path + 'soft_final_model2.pkl'
test_path = path + 'data_test_5.csv'
df_test = pd.read_csv(test_path)

df_test.info()

df_test['PreferedOrderCat'] = df_test['PreferedOrderCat'].replace({'Mobile': 'Mobile Phone'})
KATEGORI_LEMAH = ['Grocery', 'Others', 'Mobile Phone']
df_test['PreferedOrderCat'] = df_test['PreferedOrderCat'].replace(KATEGORI_LEMAH, 'Other_Product')
df_test['Tenure_Complain_Interaction'] = df_test['Tenure'] * df_test['Complain']
df_test['Cashback_per_Tenure'] = df_test['CashbackAmount'] / (df_test['Tenure'] + 1)

X_test = df_test.drop(columns='Churn')
y_test = df_test['Churn']
cat_cols = X_test.select_dtypes(include=['object']).columns


with open(model_path, 'rb') as f:
    soft_voting_model = pickle.load(f)

import warnings
THRESHOLD = 0.47
with warnings.catch_warnings():
    warnings.filterwarnings("ignore", category=UserWarning, message=".*unknown categories.*")
    y_pred_proba = soft_voting_model.predict_proba(X_test)[:, 1]
    y_pred = (y_pred_proba >= THRESHOLD).astype(int)


print(f"Model Loaded: {model_path.split('/')[-1]}")
print("Soft Voting Model Accuracy:", accuracy_score(y_test, y_pred))
print("\nClassification Report:")
print(classification_report(y_test, y_pred))

# Visualisasi Confusion Matrix
cm = confusion_matrix(y_test, y_pred)
plt.figure(figsize=(8,6))
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues')
plt.xlabel('Predicted')
plt.ylabel('Actual')
plt.title('Confusion Matrix Soft Voting (Testing)')
plt.show()

